// 3D Voxel Glyph Map extracted from assets/input.js + lowercase Latin/Cyrillic extensions
export type VoxelCoords = ReadonlyArray<readonly [number, number]>;

function glyph(rows: readonly string[], yOffset = 0): VoxelCoords {
  const coords: Array<readonly [number, number]> = [];
  for (let r = 0; r < rows.length; r++) {
    const line = rows[r];
    for (let c = 0; c < line.length; c++) {
      if (line[c] === "#") coords.push([c, r + yOffset]);
    }
  }
  return coords;
}

